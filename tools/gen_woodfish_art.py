#!/usr/bin/env python3

from gen_icons import draw_fish, draw_mallet, write_assets

_TRANSPARENT = (0.0, 0.0, 0.0, 0.0)


def draw_fish_art(nx, ny):
    return draw_fish(50 + nx * 33.6, 57.8 + ny * 25.8, _TRANSPARENT, rim=0.65)


def draw_mallet_art(nx, ny):
    return draw_mallet((nx + 1.0) * 66, (ny + 1.0) * 26, _TRANSPARENT)


if __name__ == "__main__":
    write_assets(
        "db_woodfish_art",
        [
            ("db_art_woodfish_lg", (224, 172), draw_fish_art),
            ("db_art_mallet_lg", (132, 52), draw_mallet_art),
            ("db_art_woodfish_sm", (104, 80), draw_fish_art),
            ("db_art_mallet_sm", (64, 26), draw_mallet_art),
        ],
        "Generated by tools/gen_woodfish_art.py",
    )
